import assert from 'node:assert/strict';
import {VERSION,SYMBOLS,initialState,advanceDaily,signal} from '../lib/trend-daily-long.js';
const time=d=>Date.parse(d+'T14:30:00Z');
function bar(date,o=100,h=101,l=99,c=100){return {date,t:time(date),endT:time(date)+6.5*3600000,o,h,l,c,v:100}}
const history=Array.from({length:230},(_,i)=>{const date=new Date(Date.parse('2025-01-01')+i*86400000).toISOString().slice(0,10);return bar(date)});
const last=history.at(-1).date,next=new Date(Date.parse(last)+86400000).toISOString().slice(0,10);
const state=initialState(last+'T22:00:00Z','hash'),before=JSON.stringify(state);
const series=Object.fromEntries([...SYMBOLS,'SPY'].map(symbol=>[symbol,history]));
assert.equal(advanceDaily(state,series,last+'T23:00:00Z').sessions.length,0,'No launch backfill');
assert.equal(JSON.stringify(state),before);
state.models.baseline.pending=[{id:'baseline|AAPL|'+last,symbol:'AAPL',observedAt:last+'T22:00:00Z',snapshot:{atr:2},status:'pending_entry'}];
const source=Object.fromEntries([...SYMBOLS,'SPY'].map(symbol=>[symbol,[...history,bar(next,100,105,99,104)]]));
const a=advanceDaily(state,source,next+'T22:00:00Z');
assert.equal(a.models.baseline.trades.length,1);
assert.equal(a.models.baseline.trades[0].dir,1);
assert.equal(a.models.baseline.trades[0].quantity,24);
assert.equal(a.models.baseline.pending.length,0);
const retry=advanceDaily(a,source,next+'T23:00:00Z');
assert.deepEqual(retry.models,a.models,'Retry must not reenter, settle or credit cash twice');
const broken=structuredClone(source);broken.MSFT.pop();assert.throws(()=>advanceDaily(a,broken,next+'T23:00:00Z'),/Session mismatch/);
const third=new Date(Date.parse(next)+86400000).toISOString().slice(0,10);
const gap=Object.fromEntries([...SYMBOLS,'SPY'].map(symbol=>[symbol,[...source[symbol],bar(third,90,92,89,91)]]));
const b=advanceDaily(a,gap,third+'T22:00:00Z'),p=b.models.baseline.trades[0];
assert.equal(p.status,'closed');assert.equal(p.exitReason,'gap_open');assert.equal(p.exitPrice,90*(1-.0005));
assert.ok(Math.abs(b.models.baseline.cash-10000-p.pnl)<1e-8);
assert.equal(b.benchmarks.date,third);
const rows=history.map((r,i)=>({...r,o:100+i/10,h:101+i/10,l:99+i/10,c:100+i/10}));
rows.at(-1).h=200;rows.at(-1).c=199;
assert.ok(signal(rows,rows));
const leak=signal(rows,rows);assert.ok(leak.dailySma<199,'Current close excluded from trend SMA');
assert.equal(VERSION,'trend-daily-long-v1');
console.log('Daily long-only: launch cutoff, funded sizing, retry, missing data, adverse gap fill, independent cash reconciliation and causal trend tests passed');
const dividendSource=structuredClone(gap);
dividendSource.AAPL.at(-1).dividend=1;
const paid=advanceDaily(a,dividendSource,third+'T22:00:00Z');
assert.ok(Math.abs(paid.models.baseline.cash-b.models.baseline.cash-24)<1e-8);
const split=structuredClone(gap);split.AAPL.at(-1).split=true;
assert.throws(()=>advanceDaily(a,split,third+'T22:00:00Z'),/Split requires review/);
const crowded=initialState(last+'T22:00:00Z','hash');
crowded.models.baseline.pending=SYMBOLS.map(symbol=>({id:symbol,symbol,observedAt:last+'T22:00:00Z',snapshot:{atr:2},status:'pending_entry'}));
const limited=advanceDaily(crowded,source,next+'T22:00:00Z');
assert.equal(limited.models.baseline.trades.length,4);
assert.equal(limited.models.baseline.skipped.length,8);
assert.ok(limited.models.baseline.cash>=0);
