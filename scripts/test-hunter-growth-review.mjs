import assert from 'node:assert/strict';
import {summarizeGrowthReview,growthVolumeGroup,refreshGrowthProjection} from '../lib/hunter-growth-review.js';
const episode=(id,startDate,volume)=>({episodeId:id,symbol:id,scope:'stage',entryStage:'Attractive Growth',startDate,decision:{maxRvol5:volume,avgDollar20:4000000,dist20:8,sector:'Industrials',freshHighBreakAge:0}});
const es=[episode('old','2026-10-01',2),episode('new','2026-10-19',2),episode('other','2026-10-19',1),episode('missing','2026-10-19',null)];
const os=es.map(e=>({outcomeId:e.episodeId+'h5',episodeId:e.episodeId,symbol:e.symbol,scope:e.scope,entryStage:e.entryStage,decisionDate:e.startDate,targetDate:e.episodeId==='old'?'2026-10-08':'2026-10-26',horizonSessions:5,returnPct:e.symbol==='other'?-3:2,benchmarkReturnPct:1,stageAtHorizon:'Outside active stages'}));
const saved=JSON.stringify({es,os});
const r=summarizeGrowthReview({episodes:es,outcomes:os,asOf:'2026-10-26'});
assert.equal(r.retrospective.stage[5].baseline.observations,1);
assert.equal(r.prospective.stage[5].baseline.observations,3);
assert.equal(r.prospective.stage[5].volume.spike.meanExcessPct,1);
assert.equal(r.prospective.stage[5].volume.no_spike.meanExcessPct,-4);
assert.equal(r.prospective.stage[5].volume.unknown.observations,1);
assert.equal(r.prospectiveDecisions.stage.total,3);
assert.equal(r.prospective.stage[5].extension['6to10'].observations,3);
assert.equal(r.prospective.stage[5].breakout.recent.outsideActiveStages,3,'stage exits are counted, not invented failed-breakout trades');
assert.equal(summarizeGrowthReview({episodes:es,outcomes:os,asOf:'2026-10-23'}).prospective.stage[5].baseline.observations,0);
assert.equal(summarizeGrowthReview({episodes:es,outcomes:os,asOf:'2026-10-16'}).prospectiveDecisions.stage.total,0);
assert.equal(JSON.stringify({es,os}),saved);
assert.throws(()=>summarizeGrowthReview({episodes:es,outcomes:[...os,os[0]],asOf:'2026-10-26'}),/duplicate/);
assert.throws(()=>summarizeGrowthReview({episodes:[],outcomes:os,asOf:'2026-10-26'}),/mismatch/);
assert.throws(()=>summarizeGrowthReview({asOf:'2026-99-99'}),/cutoff/);
const flagged=summarizeGrowthReview({episodes:es,outcomes:os.map(o=>({...o,maxAdverseExcursionPct:-86})),asOf:'2026-10-26'}).prospective.stage[5].baseline;
assert.equal(flagged.sourceReviewCount,3);
assert.equal(flagged.sensitivityWithoutFlagged.meanExcessPct,null);
assert.equal(growthVolumeGroup({maxRvol5:2,avgDollar20:null}),'unknown');
const monitor={version:'hunter-monitor-v1',marketAsOf:'2026-10-16',generatedAt:'original',rows:[{symbol:'keep',price:123,status:'progress'}]};
const refreshed=refreshGrowthProjection(monitor,{sessions:[{marketDate:'2026-10-16'}],episodes:es,outcomes:os},'later');
assert.equal(refreshed.generatedAt,'original');
assert.equal(refreshed.rows,monitor.rows);
assert.equal(refreshed.growthReview.prospectiveDecisions.stage.total,0);
assert.equal(refreshGrowthProjection(monitor,{sessions:[{marketDate:'2026-10-19'}]},'later'),null);
console.log('Growth research: immutable joins, frozen start, missingness and source sensitivity passed');
