import fs from 'node:fs';
import path from 'node:path';
import {parseJsonl} from '../lib/healthy-trend-pullback-forward.js';
import {auditForwardStore} from '../lib/healthy-trend-pullback-forward-audit.js';
const root=process.env.HTP_FORWARD_DIR||'data/research/healthy-trend-pullback-forward';
const read=name=>fs.existsSync(path.join(root,name))?parseJsonl(fs.readFileSync(path.join(root,name),'utf8')):[];
const audit=auditForwardStore({root,inputs:read('inputs.jsonl'),observations:read('observations.jsonl'),outcomes:read('outcomes.jsonl'),runs:read('runs.jsonl')});
fs.mkdirSync(root,{recursive:true});
fs.writeFileSync(path.join(root,'audit.json'),JSON.stringify(audit,null,2)+'\n');
console.log(JSON.stringify(audit,null,2));
if(audit.failedChecks)process.exitCode=1;
