import assert from 'node:assert/strict';
import {buildHunterMonitor} from '../lib/hunter-monitor.js';
import {hunterMonitorReport} from '../lib/telegram-fa.js';
const day=s=>Date.parse(s+'T00:00Z')/1000;
const sessions=[{marketDate:'2026-10-05',classified:[{symbol:'OUT.TO',stage:'Recovery'}],stagePicks:{Recovery:[{symbol:'OUT.TO'}]}},{marketDate:'2026-10-06',classified:[],stagePicks:{}}];
const episode={scope:'stage',symbol:'OUT.TO',startDate:'2026-10-05',entryStage:'Recovery',decision:{price:10,localLow:9,name:'A & <B>'}};
const episodes=[episode,{...episode,scope:'integrated'}, {...episode,startDate:'2026-10-06'}, {...episode,symbol:'MISS.TO'}, {...episode,symbol:'NEW.TO',startDate:'2026-10-06'}];
const symbolRows=new Map([['OUT.TO',[{t:day('2026-10-05'),close:10,high:10,low:9},{t:day('2026-10-06'),close:8,high:9,low:8},{t:day('2026-10-07'),close:20,high:20,low:20}]],['NEW.TO',[{t:day('2026-10-06'),close:10,high:10,low:10}]]]);
const benchmarkRows=[{t:day('2026-10-05'),close:100},{t:day('2026-10-06'),close:101}];
const before=JSON.stringify({sessions,episodes});
const d=buildHunterMonitor({sessions,episodes,symbolRows,benchmarkRows});
assert.equal(JSON.stringify({sessions,episodes}),before,'derived monitor never rewrites decisions');
assert.equal(d.rows.length,3,'deduplicate scope and repeat appearances by first symbol selection');
const out=d.rows.find(x=>x.symbol==='OUT.TO');
assert.equal(out.surfaced,false);assert.equal(out.currentStage,null);assert.equal(out.status,'support_broken');
assert.ok(Math.abs(out.sinceSelectionPct+20)<1e-10,'do not leak future rows into monitor');
assert.ok(Math.abs(out.excessReturnPct+21)<1e-10);
assert.equal(d.rows.find(x=>x.symbol==='MISS.TO').sinceSelectionPct,null,'missing quotes never become zero');
assert.equal(d.rows.find(x=>x.symbol==='NEW.TO').status,'new');
assert.equal(d.rows.find(x=>x.symbol==='NEW.TO').sinceSelectionPct,null,'new selection has no forward return');
const alreadyBroken=buildHunterMonitor({sessions,episodes:[{...episode,decision:{price:10,localLow:12}}],symbolRows,benchmarkRows});
assert.notEqual(alreadyBroken.rows[0].status,'support_broken','a level already above selection price must not be reported as a new support failure');
assert.equal(d.summary.missing,1);assert.equal(d.summary.down,1);
const large={...d,rows:Array.from({length:42},(_,i)=>({...out,symbol:'S'+i+'.TO'}))};
const messages=Array.from({length:6},(_,i)=>hunterMonitorReport(large,i).text);
assert.ok(messages.every(s=>s.length<3900));
for(let i=0;i<42;i++)assert.ok(messages.some(s=>s.includes('S'+i+'.TO')),'every removed pick stays accessible');
assert.match(hunterMonitorReport(d).text,/خارج از فهرست منتخب؛ پیگیری ادامه دارد/);
console.log('Hunter monitor continuity, missing data, future isolation and pagination: ok');
