import assert from 'node:assert/strict';
import {ichimoku,priorWeeks,signalAssessment,advanceTrade,updateSymbol,completedDaily} from '../lib/ichimoku/engine.mjs';
const DAY=86400000,HOUR=3600000;
const rules={tenkan:9,kijun:26,senkouB:52,displacement:26,atrBars:14,liquidityBars:20,minAverageDollarVolume:1000000,initialStopAtr:2,maxHoldBars:60,stockEntryWaitHours:120,cryptoEntryWaitHours:36};
const rows=Array.from({length:800},(_,i)=>{const t=Date.parse('2024-01-01T00:00Z')+i*DAY,c=100+i*.2;return {t,endT:t+DAY,date:new Date(t).toISOString().slice(0,10),o:c-.1,h:c+1,l:c-1,c,v:100000}});
const i=rows.length-1;
rows[i-1].c=250;rows[i-1].o=251;
rows[i].c=260;rows[i].o=253;rows[i].h=261;rows[i].l=252;
const result=signalAssessment(rows,i,rules,'crypto');
assert.equal(result.reason,'signal');assert.equal(result.signal.dir,1);
assert.equal(result.signal.signalSnapshot.dailyAsOf,rows[i].date);
const values=ichimoku(rows,i,rules),origin=i-26;
const mid=(n)=>(Math.max(...rows.slice(origin-n+1,origin+1).map(b=>b.h))+Math.min(...rows.slice(origin-n+1,origin+1).map(b=>b.l)))/2;
assert.equal(values.spanA,(mid(9)+mid(26))/2);assert.equal(values.spanB,mid(52));
const future=rows.concat([{...rows[i],t:rows[i].t+DAY,date:'2099-01-01',h:1e9,c:1e9}]);
assert.deepEqual(signalAssessment(future,i,rules,'crypto'),result,'appended future bars never change earlier decision');
const week=priorWeeks(rows,rows[i].date);
assert.ok(week.at(-1).date<rows[i].date);
assert.equal(signalAssessment(rows.slice(-100),99,rules,'crypto').reason,'weekly_cloud_warmup');
const mirrored=rows.map(b=>({...b,o:500-b.o,h:500-b.l,l:500-b.h,c:500-b.c}));
assert.equal(signalAssessment(mirrored,i,rules,'crypto').signal.dir,-1,'short is symmetric');
const weakVolume=rows.map(b=>({...b,v:1}));
assert.equal(signalAssessment(weakVolume,i,rules,'stock').reason,'liquidity');
const observedAt=new Date(rows[i].endT+60000).toISOString();
assert.equal(completedDaily(rows,'crypto',new Date(rows[i].endT-1).toISOString()).length,rows.length-1);
const opts={symbol:'FIXTURE',mode:'crypto',rules,forwardStart:new Date(rows[i].t).toISOString(),observedAt,runKey:'fixture',configHash:'frozen'};
const pending=updateSymbol([],[],rows,new Map(),opts);
assert.equal(pending.length,1);assert.equal(pending[0].status,'pending_entry');
assert.deepEqual(updateSymbol(pending,[],rows,new Map(),opts),pending,'same daily signal never duplicated');
assert.equal(updateSymbol([],[],rows,new Map(),{...opts,forwardStart:new Date(rows[i].endT+1).toISOString()}).length,0,'prelaunch decisions excluded');
assert.equal(updateSymbol([],[],rows,new Map(),{...opts,observedAt:new Date(rows[i].endT+40*HOUR).toISOString()}).length,0,'stale signals not backfilled');
const start=rows[i].endT,bars=Array.from({length:4},(_,n)=>({t:start+n*4*HOUR,endT:start+(n+1)*4*HOUR,o:260,h:261,l:259,c:260}));
const now=new Date(start+20*HOUR).toISOString();
const opened=advanceTrade(pending[0],bars.slice(0,2),rows,new Map(),rules,'crypto',now);
assert.equal(opened.entryT,new Date(bars[1].t).toISOString(),'never fill an open before first observation');
assert.equal(opened.status,'open');assert.equal(opened.stop,260-2*result.signal.signalSnapshot.atr14);
assert.equal(advanceTrade(opened,bars.slice(0,2),rows,new Map(),rules,'crypto',now).holdingBars,opened.holdingBars,'idempotent lifecycle');
assert.equal(advanceTrade(pending[0],bars,rows,new Map(),rules,'crypto',new Date(start+5*HOUR).toISOString()).status,'pending_entry','unfinished entry bar excluded');
const gapBars=structuredClone(bars);gapBars[2].o=opened.stop-3;gapBars[2].l=opened.stop-4;
const loss=advanceTrade(opened,gapBars,rows,new Map(),rules,'crypto',now);
assert.equal(loss.status,'closed');assert.ok(loss.R<-1);assert.equal(loss.exitReason,'stop_gap_open');
assert.deepEqual(advanceTrade(loss,[],[],new Map(),rules,'crypto',now),loss,'closed outcome immutable');
assert.equal(advanceTrade(opened,bars,rows,new Map([[2,{missing:true}]]),rules,'crypto',now).lifecycleDataGap.type,'holding_path_gap');
const timeExit=advanceTrade(opened,bars,rows,new Map(),{...rules,maxHoldBars:2},'crypto',now);
assert.equal(timeExit.exitReason,'max_hold_close');
const exitDecision={...opened,kijunExitDecision:{observedAt:new Date(bars[2].t+60000).toISOString()}};
const exited=advanceTrade(exitDecision,bars,rows,new Map(),rules,'crypto',now);
assert.equal(exited.exitPriceAssumed,bars[3].o);assert.equal(exited.executionAudit.exitBarStartT,new Date(bars[3].t).toISOString(),'exit uses next observed open even if later daily state recovers');
assert.equal(advanceTrade({...pending[0],decisionAvailableAt:new Date(start+50*HOUR).toISOString()},bars,rows,new Map(),rules,'crypto',new Date(start+55*HOUR).toISOString()).cancelReason,'entry_window_expired');
console.log('Ichimoku V1: displaced cloud, completed prior weeks, causal decisions, symmetric sides, liquidity, future-data isolation, entry/exit timing, gaps and immutable outcomes passed');
