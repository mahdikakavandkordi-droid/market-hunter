import assert from 'node:assert/strict';
import '../home-overview.js';
const {build}=globalThis.MarketHunterOverview;
const names={TSX:'TSX Composite',SP500:'S&P 500',NASDAQ100:'Nasdaq-100',GOLD:'Gold',SILVER:'Silver',BTC:'Bitcoin',ETH:'Ethereum'};
const row=(key,extra={})=>({key,name:names[key],asOf:'2026-10-19',regime:'Mixed',condition:'Weakening',current:{returns:{d5:1,d20:0}},freshness:{status:'fresh'},...extra});
const fresh=x=>({usable:x?.freshness?.status==='fresh',status:x?.freshness?.status||'missing'});
const markets=Object.keys(names).map(k=>row(k));
const daily={markets:markets.map(m=>({...m,levels:{bullishTrigger:110,bearishTrigger:90}})),groups:[{label:'Equities',state:'Weakening'},{label:'Metals',state:'Weakening'},{label:'Crypto',state:'Mixed'}],highestAttention:['BTC','SILVER','SP500'],watchNext:[]};
const original=JSON.stringify({markets,daily});
const full=build({markets},daily,fresh);
assert.equal(full.current,7);assert.equal(full.weakening,7);assert.equal(full.equityComparison.length,3);
assert.equal(full.equityComparison[0].d20,0,'zero is a real recorded return');
assert.deepEqual(full.attention.map(x=>x.key),['BTC','SILVER','SP500']);
assert.equal(JSON.stringify({markets,daily}),original,'never mutate research inputs');
const partial=build({markets:markets.map(m=>m.key==='BTC'?{...m,freshness:{status:'stale'}}:m)},daily,fresh);
assert.equal(partial.current,6);assert.equal(partial.weakening,6);assert.equal(partial.groups.find(x=>x.key==='crypto').complete,false);
assert.equal(partial.groups.find(x=>x.key==='crypto').state,null);assert.ok(!partial.attention.some(x=>x.key==='BTC'));
const missing=build({markets:markets.filter(m=>m.key!=='ETH')},daily,fresh);
assert.equal(missing.groups.find(x=>x.key==='crypto').complete,false,'a missing member cannot pass every([]) as current');
assert.equal(missing.current,6);assert.equal(missing.markets.find(x=>x.key==='ETH').record,null);
const differentDate=build({markets:markets.map(m=>m.key==='SP500'?{...m,asOf:'2026-10-16'}:m)},daily,fresh);
assert.equal(differentDate.equityComparison.length,0,'do not compare equity returns with different endpoints');
assert.ok(!differentDate.attention.some(x=>x.key==='SP500'),'do not borrow levels from a different report session');
const duplicates=build({markets:[...markets,row('TSX')]},daily,fresh);
assert.equal(duplicates.current,6,'ambiguous duplicate source identity is not a usable assessment');
assert.equal(duplicates.equityComparison.length,0);
assert.equal(build({markets:[row('TSX',{asOf:'invalid'})]},daily,fresh).current,0);
assert.equal(build({markets:[row('TSX',{asOf:'2026-02-30'})]},daily,fresh).current,0);
assert.equal(build({markets:[row('TSX',{regime:null})]},daily,fresh).current,0);
assert.equal(build({markets:[row('TSX',{current:{returns:{d20:null}}})]},daily,fresh).equityComparison.length,0);
assert.equal(build({},daily,fresh).hasData,false);
assert.equal(build({markets},daily,()=>({usable:false})).current,0);
console.log('Home overview: source identity, current coverage, aligned comparisons, recorded attention and immutability passed');
